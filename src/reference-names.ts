/** `entry` with the reference app's names, when it has them. */
export function withReferenceNames<T extends { id: string; name: string; shortName: string; metadata: { title: string; shortTitle: string } }>(entry: T): T {
  const names = REFERENCE_NAMES[entry.id];
  if (!names) return entry;
  const [title, shortTitle] = names;
  return { ...entry, name: title, shortName: shortTitle, metadata: { ...entry.metadata, title, shortTitle } };
}
