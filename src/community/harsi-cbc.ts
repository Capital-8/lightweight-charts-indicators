/**
 * HARSI+CBC
 *
 * Heikin-Ashi candles of the zero-centred RSI (RSI - 50) of close, high and low: open = previous close RSI,
 * high / low = the larger / smaller of the high and low RSI, close = the average of the four; the candle open is
 * smoothed as a Heikin-Ashi open ((open[1] * smoothing + close[1]) / (smoothing + 1)). A zero-centred RSI of the
 * source (optionally smoothed: (previous + current) / 2) is drawn as a line with a shadow and as a histogram, and an
 * optional stochastic of that RSI (scaled) as K / D lines or a ribbon fill. Bands at OB / OS levels with fills.
 * CBC flip: the state turns bullish when the close is above the previous high and bearish when the close is below
 * the previous low; a flip colours the background and draws a triangle.
 * Alerts (alertcondition, `alerts` of the result): 'Bears' on a bearish flip, 'Bulls' on a bullish flip.
 *
 * Reference: "HARSI+CBC" by mehmetbezgincan
 * Licence: Mozilla Public License 2.0, as the original Pine script (https://mozilla.org/MPL/2.0/).
 * Original notice: This source code is free to use, copy, and alter in any way you choose. ...but credit is always
 * nice :) HARSI Originally by @JayRogers. CBC Flip Originally by @friksa & @AsiaRoo
 */

